/** Пространство центрального кэша (AppCache) для эфирного времени. */
export const AIRTIME_CACHE_APP = 'airtime' as const;

/** Группа месячных ячеек — для пакетного сброса/инспекции в /app-cache. */
export const AIRTIME_CACHE_GROUP_MONTH = 'month' as const;

/** Группа дневных ячеек текущего месяца. */
export const AIRTIME_CACHE_GROUP_DAY = 'day' as const;

/**
 * TTL дневной ячейки прошедшего дня текущего месяца: 90 суток.
 * День неизменяем; ячейка нужна лишь пока месяц не закрылся (после
 * закрытия работает месячная ячейка) — 90 дней с запасом. Чистка —
 * как у месячных (Redis TTL + почасовой purge БД).
 */
export const AIRTIME_DAY_TTL_SECONDS = 90 * 24 * 3600;

/**
 * TTL ячейки прошлого месяца: 180 суток.
 *
 * Как чистится: Redis-ключ протухает сам; строку app_cache (MySQL)
 * удаляет почасовой purgeExpired-cron AppCacheService. После протухания
 * следующий запрос за этот месяц честно пересчитает его из Bitrix и
 * снова закэширует — «не смотрят — не храним». Данные прошлых месяцев
 * неизменяемы, поэтому TTL можно смело увеличивать; 180 дней — баланс
 * между объёмом (100 сотрудников × 24 мес ≈ 300 КБ на портал) и
 * скоростью годовых отчётов.
 *
 * Ручной сброс: POST /app-cache/reset { app: 'airtime', domain }.
 *
 * 3 года: данные прошлых месяцев неизменяемы, кэшировать можно сколь
 * угодно долго — предел лишь объём (100 сотрудников × 36 мес × ~150 Б
 * ≈ 0.5 МБ/портал даже на 3 года). Прогретые годовые/трёхлетние отчёты
 * отдаются мгновенно всем потребителям (фрейм, публичные ссылки) на том
 * же бэкенде. Если данные Bitrix ретроспективно поправят — форс-сброс
 * ручкой /app-cache/reset или /kpi-airtime/cache/reset.
 */
export const AIRTIME_MONTH_TTL_SECONDS = 3 * 365 * 24 * 3600;
