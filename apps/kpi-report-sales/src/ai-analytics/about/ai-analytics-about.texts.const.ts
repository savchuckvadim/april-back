/** Доля 0..1 → проценты: 0,8 → 80. */
const pct = (share: number): number => Math.round(share * 100);
/** Доля 0..1 → «8 из 10». */
const outOfTen = (share: number): string => `${Math.round(share * 10)} из 10`;

/** Совет «больше звонков» — только при почти верной пользе. */
