/** Код региона Москвы в справочнике регионов. */
export const MOSCOW_REGION_CODE = 'msk';

/**
 * Вес регионального блока в весе комплекта: Москва 1, остальные 0.5
 * (решение владельца). Колонки веса в таблице регионов нет, значение
 * выводится из кода региона.
 */
export const regionWeight = (code: string): number =>
    code === MOSCOW_REGION_CODE ? 1 : 0.5;
