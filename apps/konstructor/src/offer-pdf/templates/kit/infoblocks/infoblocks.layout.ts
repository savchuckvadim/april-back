import { contentWidth, type OfferPdfTheme } from '../theme/offer-pdf-theme';

/**
 * Геометрия наполнения и правила разрыва по страницам.
 *
 * РАЗРЫВ ДЛИННЫХ ОПИСАНИЙ (КП 15.11: «Большая библиотека юриста» налезала
 * на «...бухгалтера»). Неразрывный блок выше листа react-pdf кладёт как есть
 * и только пишет предупреждение: текст уходит под подвал, следующий блок
 * рисуется поверх, хвост теряется. Поэтому блок до KEEP_WHOLE_LINES строк
 * переезжает целиком, а длиннее — режется по странице. Раскладку считает
 * движок; оценка строк лишь выбирает режим, и ошибка в пару строк не важна.
 */

/** Толщина рамки таблицы */
export const FRAME = 0.75;
/** Толщина внутренних линий таблицы */
export const GRID = 0.5;

/** Колонка названий — треть строки таблицы (34 %) */
export const nameColumnWidth = (theme: OfferPdfTheme): number =>
    (contentWidth(theme) - FRAME * 2) * 0.34;

/** Символов в строке колонки описания (две трети ширины, 8,5 pt) — по замеру КП */
export const TABLE_DESC_CHARS = 80;
/** Символов в строке описания в списке (вся ширина) */
export const LIST_DESC_CHARS = 120;
/** До скольких строк блок переезжает на новую страницу целиком */
export const KEEP_WHOLE_LINES = 12;
/** Строк описания, которые остаются вместе по обе стороны разрыва */
export const MIN_SPLIT_LINES = 3;
/** Место под начало длинного блока: три строки 8,5 pt × 1,35 и поля ячейки */
export const SPLIT_PRESENCE = 44;
/** Шапка группы в таблице: строка 8,5 pt и поля ячейки */
export const TABLE_GROUP_HEAD = 18;
/** Заголовок группы в списке: 11,5 pt × 1,35 и отступы */
export const LIST_GROUP_HEAD = 30;

/**
 * Заголовок комплекта в разделе наполнения по комплектам: полоса акцента
 * слева, название комплекта и под ним подпись поставки. Заголовок и первая
 * группа комплекта держатся на одном листе (HeadWithFirst).
 */
/** Отступ сверху: комплекты отделены друг от друга и от заголовка раздела */
export const COMPLECT_HEAD_MARGIN_TOP = 14;
/** Отступ снизу до заголовка первой группы или таблицы */
export const COMPLECT_HEAD_MARGIN_BOTTOM = 2;
/** Толщина полосы акцента слева от заголовка комплекта */
export const COMPLECT_HEAD_BAR = 3;
/** Поле между полосой и текстом заголовка комплекта */
export const COMPLECT_HEAD_PADDING = 6;
/** Интерлиньяж названия комплекта — по его собственному кеглю */
export const COMPLECT_TITLE_LINE_HEIGHT = 1.15;

/** Кегль названия комплекта: на шаг крупнее заголовка группы и меньше заголовка раздела */
export const complectTitleSize = (lg: number): number => lg + 1;

/**
 * Блок «Наполнение наборов для сравнения» после наполнения общего набора:
 * общий заголовок блока (кегль заголовка раздела), у каждого набора плашка с
 * его заголовком (заливка шапки таблицы цен, как у заголовков наборов там) и
 * под ней разделы комплектов набора. Заголовок блока, плашка первого набора,
 * заголовок первого комплекта и первая группа с первым пунктом держатся на
 * одном листе (HeadWithFirst).
 */
/** Отступ сверху заголовка блока: блок отделён от наполнения общего набора */
export const ALTERNATIVE_BLOCK_MARGIN_TOP = 22;
/** Отступ снизу заголовка блока: до плашки первого набора её собственный отступ */
export const ALTERNATIVE_BLOCK_MARGIN_BOTTOM = 0;
/** Отступ сверху плашки набора: наборы отделены друг от друга */
export const ALTERNATIVE_SET_MARGIN_TOP = 14;
/** Отступ снизу плашки набора до заголовка первого комплекта */
export const ALTERNATIVE_SET_MARGIN_BOTTOM = 0;
/** Поле плашки набора по вертикали */
export const ALTERNATIVE_SET_PADDING_VERTICAL = 4;
/** Поле плашки набора по горизонтали */
export const ALTERNATIVE_SET_PADDING_HORIZONTAL = 6;
/** Отступ сверху заголовка комплекта, когда над ним плашка набора */
export const COMPLECT_HEAD_MARGIN_TOP_UNDER_SET = 8;
