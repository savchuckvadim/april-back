import { contentWidth, type OfferPdfTheme } from '../theme/offer-pdf-theme';

/**
 * Геометрия наполнения и правила разрыва по страницам.
 *
 * РАЗРЫВ ДЛИННЫХ ОПИСАНИЙ (КП 15.11: «Большая библиотека юриста» налезала
 * на «...бухгалтера»). Неразрывный блок выше листа react-pdf кладёт как есть
 * и только пишет предупреждение: текст уходит под подвал, следующий блок
 * рисуется поверх, хвост теряется. Поэтому блок до KEEP_WHOLE_LINES строк
 * переезжает целиком, а длиннее — режется по странице. Раскладку считает
 * движок; оценка строк лишь выбирает режим, и ошибка в пару строк не важна.
 */

/** Толщина рамки таблицы */
export const FRAME = 0.75;
/** Толщина внутренних линий таблицы */
export const GRID = 0.5;

/** Колонка названий — треть строки таблицы (34 %) */
export const nameColumnWidth = (theme: OfferPdfTheme): number =>
    (contentWidth(theme) - FRAME * 2) * 0.34;

/** Символов в строке колонки описания (две трети ширины, 8,5 pt) — по замеру КП */
export const TABLE_DESC_CHARS = 80;
/** Символов в строке описания в списке (вся ширина) */
export const LIST_DESC_CHARS = 120;
/** До скольких строк блок переезжает на новую страницу целиком */
export const KEEP_WHOLE_LINES = 12;
/** Строк описания, которые остаются вместе по обе стороны разрыва */
export const MIN_SPLIT_LINES = 3;
/** Место под начало длинного блока: три строки 8,5 pt × 1,35 и поля ячейки */
export const SPLIT_PRESENCE = 44;
/** Шапка группы в таблице: строка 8,5 pt и поля ячейки */
export const TABLE_GROUP_HEAD = 18;
/** Заголовок группы в списке: 11,5 pt × 1,35 и отступы */
export const LIST_GROUP_HEAD = 30;
