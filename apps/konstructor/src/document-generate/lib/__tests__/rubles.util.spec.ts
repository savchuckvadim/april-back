import { getCaseMonthes } from '../rubles.util';

describe('getCaseMonthes', () => {
    it('1 месяц, 2–4 месяца, 5–20 месяцев', () => {
        expect([1, 2, 3, 4, 5, 6, 12].map(getCaseMonthes)).toEqual([
            'месяц',
            'месяца',
            'месяца',
            'месяца',
            'месяцев',
            'месяцев',
            'месяцев',
        ]);
    });

    it('11–14 — «месяцев», 21–24 — снова по последней цифре', () => {
        expect([11, 13, 14, 21, 22, 24].map(getCaseMonthes)).toEqual([
            'месяцев',
            'месяцев',
            'месяцев',
            'месяц',
            'месяца',
            'месяца',
        ]);
    });
});
