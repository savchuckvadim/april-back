export enum ClientTypeEnum {
    ORG_STATE = 'org_state',
    ORG = 'org',
    IP = 'ip',
    FIZ = 'fiz',
    /**
     * Адвокатское образование. Задел на будущее: в поле карточки компании
     * (`PBX_CLIENT_TYPE.LAYER`) и в составе формы отчёта о поставке код
     * `advokat` уже встречается, а в докблоке миграции 2026_09_15_100300
     * заказчик перечисляет «физ, юр, бюджетники, адвокаты».
     *
     * Почему добавление безопасно: ни одна ветка в коде не делает
     * exhaustive switch по ClientTypeEnum — все 13 обращений это сравнения
     * `=== FIZ` либо `=== ORG_STATE`. Поэтому адвокат попадает в ту же
     * ветку «не физлицо и не бюджетник», что и ORG, то есть ведёт себя
     * ровно как сегодня, пока под него не завели отдельный шаблон.
     */
    ADVOKAT = 'advokat',
}
