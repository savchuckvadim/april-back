import { EnumQuestionnaireControl } from '@lib/portal-lib/store/questionnaires';

/** Назначение анкеты: план — элемент plan-джоба, отчёт — элемент report. */
export type QuestionnaireAnswerPurpose = 'plan' | 'report';

/**
 * Ответ портальной анкеты, адресованный полю ЭЛЕМЕНТА смарта.
 *
 * Снимок собирается в основном пути отчёта (`build-questionnaire-smart-answers`)
 * из каталога и payload фрейма — БЕЗ единого вызова Битрикса, ровно как
 * `PresentationSurveySnapshot`. В элемент его раскладывает уже джоб потока:
 * только он знает id элемента, который сам же и создаёт или закрывает.
 *
 * Почему снимок, а не сырой payload: каталог на момент постановки джоба —
 * источник правды (в нём и адрес поля, и тип, и подпись варианта), а к
 * моменту выполнения джоба он может смениться. Плюс payload фрейма это
 * ДАННЫЕ, а не команда: то, чего нет в каталоге, сюда не попадает вовсе.
 */
export interface QuestionnaireSmartAnswer {
    /** `qCode:itemCode` — ключ ответа фрейма, он же ключ логов. */
    key: string;
    /** Назначение анкеты: план или отчёт. */
    purpose: QuestionnaireAnswerPurpose;
    /** Полное UF-имя поля элемента ровно как его записал каталог. */
    fieldName: string;
    /** `userTypeId` на момент привязки; null — тип неизвестен. */
    fieldType: string | null;
    control: EnumQuestionnaireControl;
    /**
     * Ответ В КАНОНЕ КАТАЛОГА: `YYYY-MM-DD` у дат, `Y`/`N` у «да/нет»,
     * КОД варианта у справочника, число строкой у денег. Перевод в формат
     * Битрикса делает {@link toSmartFieldValue} по живому полю.
     */
    value: string;
    /** Заголовок вопроса — только для внятных предупреждений в логе. */
    title: string;
    /**
     * Подпись выбранного варианта справочника; null — контрол не список.
     *
     * `bitrixId` варианта здесь нет намеренно: каталог его каналу `smart`
     * не отдаёт (идентификатор элемента списка — адрес чужой системы), и
     * резолвится он по ЖИВОМУ справочнику смарта в момент записи.
     */
    optionTitle: string | null;
}
