/**
 * НИЖНЯЯ ГРАНИЦА ПОРОГА SLA — ЧАС.
 *
 * Авария 16–17.09.2026: на портале в поле «минут на принятие» стояло 10, то
 * есть ровно тик крона. Просроченным становилось всё, что крон только что
 * передал, и один и тот же пул сделок переназначался НА КАЖДОМ ТИКЕ: заявки
 * скакали между менеджерами каждые десять минут два дня подряд. Меньше часа
 * на принятие заявки не имеет смысла ни при каких настройках.
 *
 * Решение владельца 17.09.2026: «60 мин минимум и дефолт, всё».
 */
export const SLA_MIN_MINUTES = 60;

/**
 * ДАВНОСТЬ ЗАЯВКИ ДЛЯ SLA — 3 КАЛЕНДАРНЫХ ДНЯ.
 *
 * Метку «ждёт принятия» гасит только кнопка «принять заявку», а её жмут не
 * всегда — метки копятся месяцами. 29.10.2026 (garantservisvoronezh) крон
 * брал первые по номеру: лиды сентября с удалёнными сделками и живые сделки
 * 2018 года, — и до свежей заявки (сделка 109183) не доходил.
 *
 * Решение владельца 29.10.2026: сначала свежие; назначенное больше 3 дней
 * назад не трогаем — это забытые хвосты, а не «ждёт принятия».
 */
export const SLA_MAX_AGE_DAYS = 3;

const DAY_MS = 24 * 60 * 60 * 1000;

/** Самое раннее назначение, которое SLA ещё рассматривает. */
export const slaNotBefore = (now: Date): Date =>
    new Date(now.getTime() - SLA_MAX_AGE_DAYS * DAY_MS);

/**
 * Сколько рабочих минут даётся на принятие заявки: настройка портала
 * «SLA: минут на принятие», но не меньше часа. Одно число и для срока
 * задачи при распределении по кругу, и для SLA-передачи — иначе заявку
 * забирали бы раньше срока или позже него.
 */
export const slaThresholdMinutes = (
    configured: number | null | undefined,
): number =>
    typeof configured === 'number' &&
    Number.isFinite(configured) &&
    configured >= SLA_MIN_MINUTES
        ? configured
        : SLA_MIN_MINUTES;
