/**
 * КАНОНИЧЕСКИЙ ТЕКСТ ВОПРОСОВ «Пять К» и «Хвоста» — один на всех.
 *
 * Переделка 01.09.2026: вместо пятнадцати полей-вопросов десять полей по теме,
 * а подвопросы живут ВНУТРИ значения текстом. Менеджер открывает поле и видит
 * пронумерованные вопросы, ответы пишет между ними.
 *
 * ПОЧЕМУ ЭТОТ ФАЙЛ ОДИН И ПОЧЕМУ ОН ЗДЕСЬ. Один и тот же текст нужен четырём
 * потребителям: фронт рисует им шаблон в поле ввода, бэк отличает «в поле
 * только шаблон» от «менеджер ответил», подсказка поля в Битриксе показывает
 * те же вопросы, а установщик берёт их для колонки Excel. Разъедься эти
 * четыре копии на одну формулировку — и проверка «только шаблон» начнёт
 * считать заполненным нетронутое поле. Поэтому текст ровно один, а всё
 * остальное собирается из него.
 *
 * Файл зеркалится в `@workspace/event-sales-flow` (правка — сначала здесь).
 */

/** Один блок вопросов: поле-носитель, заголовок и подвопросы по порядку. */
export interface SurveyTemplate {
    /**
     * Код поля, в которое ложится весь блок.
     *
     * Тип — union кодов реестра, а не строка: опечатка в коде должна падать
     * на компиляции, а не превращаться в блок, который молча никуда не
     * пишется.
     */
    readonly code: PbxSalesEventFieldCode;
    /** Заголовок блока — он же название поля без служебного префикса. */
    readonly title: string;
    /**
     * Подвопросы В ПОРЯДКЕ показа. Номер НЕ хранится в тексте: его проставляет
     * `buildSurveyTemplateText`, иначе перестановка вопроса требовала бы
     * переписать все номера руками — и однажды кто-нибудь этого не сделает.
     */
    readonly questions: readonly string[];
}

