/** Блок по коду поля; `null` — код не из опросника. */
export const surveyTemplateByCode = (
    code: string,
): SurveyTemplate | null =>
    SURVEY_TEMPLATES.find(template => template.code === code) ?? null;

/**
 * Текст, которым поле открывается: пронумерованные вопросы, каждый со своей
 * строки.
 *
 * Нумерация в КАЖДОМ блоке начинается с единицы — менеджер видит её внутри
 * одного поля, и сквозная нумерация через все блоки читалась бы как ошибка
 * («почему тут сразу девятый?»).
 */
export const buildSurveyTemplateText = (template: SurveyTemplate): string =>
    template.questions
        .map((question, index) => `${index + 1}. ${question}`)
        .join('\n');

/** Пробелы схлопнуты, края обрезаны — форма для сравнения, не для показа. */
const normalize = (value: string): string =>
    value.replace(/\s+/gu, ' ').trim();

/** Ведущий номер пункта («3. ») — служебный, к тексту вопроса не относится. */
const stripLeadingNumber = (line: string): string =>
    line.replace(/^\s*\d+\s*[.)]\s*/u, '');

/**
 * Разделители между вопросом и ответом, записанными в одну строку:
 * «1. Реакция клиента на цену — сказал, что дорого».
 */
const stripAnswerSeparator = (value: string): string =>
    value.replace(/^\s*[-–—:;,.]+\s*/u, '');

/**
 * Что менеджер ДОПИСАЛ к шаблону: значение поля минус сам шаблон.
 *
 * Разбор построчный, а не по регулярке от всего текста: менеджер пишет ответы
 * и следующей строкой, и в той же строке после вопроса, и оба способа обязаны
 * читаться одинаково. Строка, начинающаяся с текста вопроса, отдаёт хвост
 * после него; строка, вопросом не являющаяся, целиком считается ответом.
 *
 * Возвращает склеенный текст ответов; пустая строка означает «поле не
 * трогали».
 */
export const stripSurveyTemplate = (
    value: string,
    template: SurveyTemplate,
): string => {
    const questions = template.questions.map(normalize);
    const answers: string[] = [];

    for (const rawLine of value.split(/\r?\n/u)) {
        const line = normalize(stripLeadingNumber(rawLine));
        if (!line) continue;

        const matched = questions.find(question => line.startsWith(question));
        if (matched === undefined) {
            answers.push(line);
            continue;
        }

        const rest = stripAnswerSeparator(line.slice(matched.length));
        if (rest) answers.push(rest);
    }

    return answers.join('\n');
};

/**
 * В поле ТОЛЬКО шаблон — менеджер его не трогал.
 *
 * Зачем отдельная проверка. До переделки пустая строка означала «не
 * отвечали», и на этом стоит важное правило: пустое в портал НЕ пишется,
 * чтобы не стереть ответ, положенный кем-то другим. С шаблоном внутри поле не
 * бывает пустым НИКОГДА — в нём всегда есть вопросы. Без этой проверки
 * система считала бы заполненным то, чего никто не трогал, и записывала бы
 * шаблон поверх чужого настоящего ответа.
 *
 * СРАВНЕНИЕ ЦЕЛИКОМ, А НЕ ПОСТРОЧНЫЙ РАЗБОР — сознательный выбор после
 * разбора крайних случаев. Построчная версия («убрать все строки-вопросы,
 * посмотреть, что осталось») теряла ответы: ответ, дословно совпавший с
 * текстом вопроса, и ответ вида «5)» схлопывались в пустоту, и поле
 * считалось нетронутым. Сравнение с эталоном ошибается в другую сторону —
 * покалеченный шаблон уедет в CRM как ответ, — и это безопаснее: лишний
 * текст видно глазами, а потерянный ответ не видно никак.
 */
export const isSurveyTemplateOnly = (
    value: string | null | undefined,
    template: SurveyTemplate,
): boolean => {
    if (typeof value !== 'string') return true;
    if (!value.trim()) return true;
    return normalize(value) === normalize(buildSurveyTemplateText(template));
};

/**
 * Значение поля для записи в портал: `null`, если отвечать не стали.
 *
 * Сам шаблон в CRM уезжает вместе с ответами — так решил владелец: вопросы
 * должны быть видны и тому, кто открыл карточку мимо приложения. Поэтому
 * возвращается ИСХОДНОЕ значение целиком, а не одни ответы.
 */
export const surveyValueForPortal = (
    value: string | null | undefined,
    template: SurveyTemplate,
): string | null => {
    if (isSurveyTemplateOnly(value, template)) return null;
    return (value as string).trim();
};
