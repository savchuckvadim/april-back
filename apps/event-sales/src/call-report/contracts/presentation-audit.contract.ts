import { DEEP_ANALYSIS_CORE_RULES } from './call-deep-analysis.contract';

/**
 * Контракт КРОН-СВЕРКИ ПО ПРЕЗЕНТАЦИЯМ (Фаза 4 плана
 * ai/tasks/call-analysis-v2-plan.md, архитектура владельца 15.08.2026):
 * отдельный ежедневный прогон сопоставляет ОТЧЁТ МЕНЕДЖЕРА (поля
 * «ОП Хвост» / «ОП Пять К» / «ОП Комментарии после презентаций» на
 * сделке-презентации) с РАЗБОРОМ ЗВОНКА (hvostDone/fiveKDone и разборы).
 * Итог — запись «⚖️ Сверка с отчётом менеджера» в таймлайн смарт-элемента,
 * при расхождении — дубль в таймлайн сделки для руководителя.
 */

export const PRESENTATION_AUDIT_SCHEMA: Record<string, unknown> = {
    type: 'object',
    properties: {
        /** Текст сверки для таймлайна (по пунктам, с конкретикой). */
        comparison: { type: 'string' },
        /** Есть ли существенное расхождение отчёта с разбором. */
        mismatch: { type: 'boolean' },
        /** Короткие формулировки расхождений (пусто — расхождений нет). */
        mismatchPoints: { type: 'array', items: { type: 'string' } },
    },
    required: ['comparison', 'mismatch', 'mismatchPoints'],
    additionalProperties: false,
};

export const PRESENTATION_AUDIT_PROMPT = `${DEEP_ANALYSIS_CORE_RULES}

ТЫ — СВЕРЩИК ОТЧЁТНОСТИ. Тебе даны: (1) итоги AI-разбора звонка-презентации
и (2) отчёт менеджера в CRM по той же презентации («хвост», «5К»,
комментарии). Сопоставь их:
- Расхождение типа «приукрасил»: менеджер отметил пройденным то, чего в
  звонке НЕ БЫЛО (например «5К закрыто», а конкурент и критерии выбора не
  выяснялись) — назови каждое такое место конкретно.
- Расхождение типа «не отчитался»: в звонке БЫЛО (цена названа, дата
  назначена), а в отчёте пусто или не отмечено.
- Отчёт полностью пуст при состоявшейся презентации — это mismatch:
  «отчёт по презентации не заполнен».
- Совпадает — так и напиши: отчёт соответствует разбору, 1-2 предложения.
comparison — связный текст для руководителя: сначала вердикт одной строкой,
затем расхождения по пунктам с конкретикой из звонка и отчёта.
mismatch=true только при СУЩЕСТВЕННЫХ расхождениях (формулировки и стиль
не в счёт). НЕ пересматривай оценки разбора и не выдумывай фактов.`;

/** Данные для сверки одним запросом. */
export function buildPresentationAuditUserContent(input: {
    analysisDigest: string;
    managerReport: string;
}): string {
    return (
        `ИТОГИ AI-РАЗБОРА ЗВОНКА-ПРЕЗЕНТАЦИИ:\n${input.analysisDigest}\n\n` +
        `ОТЧЁТ МЕНЕДЖЕРА В CRM:\n${input.managerReport}`
    );
}
