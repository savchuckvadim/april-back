import { QUOTE_TIMECODE_SPEC } from './call-quote-timecode.contract';

/**
 * Контракт риск-флагов — общий для фокуса «движение сделки» и цельного
 * разбора (промпт focus-v2.4 от 20.10.2026, решение владельца 19.10.2026).
 *
 * До этого модель получала только английские коды и строку «что должно
 * попасть на стол руководителю» — и ~90 % флагов оказывались не по делу.
 * Здесь каждый флаг получает русское название, критерии, контрпримеры и
 * обязательное доказательство (riskEvidence): флаг без дословной цитаты
 * приём разбора снимает (agent-analysis-risk.util).
 */

/** riskFlags — коды справочника RISK_FLAGS смарта. */
export const RISK_FLAGS_SCHEMA = {
    type: 'array',
    items: { type: 'string', enum: [...CALL_REPORT_RISK_FLAG_CODES] },
} as const;

/** Одно доказательство флага: цитата, чья реплика, таймкоды (strict). */
export const RISK_EVIDENCE_SCHEMA = {
    type: 'object',
    properties: {
        flag: { type: 'string', enum: [...CALL_REPORT_RISK_FLAG_CODES] },
        quote: { type: 'string' },
        startSec: { type: ['number', 'null'] },
        endSec: { type: ['number', 'null'] },
        speaker: { type: 'string', enum: [...AGENT_RISK_EVIDENCE_SPEAKERS] },
    },
    required: ['flag', 'quote', 'startSec', 'endSec', 'speaker'],
    additionalProperties: false,
} as const;

export const RISK_EVIDENCE_LIST_SCHEMA = {
    type: 'array',
    items: RISK_EVIDENCE_SCHEMA,
} as const;

/**
 * Блок промпта «СИГНАЛЫ РУКОВОДИТЕЛЮ»: определения, критерии и
 * контрпримеры каждого флага, правило доказательства и правило
 * «сомневаешься — не ставь».
 */
export const RISK_FLAGS_SPEC = `СИГНАЛЫ РУКОВОДИТЕЛЮ (riskFlags и riskEvidence)
- riskFlags — коды сигналов, которые должны попасть на стол руководителю.
  ГЛАВНОЕ ПРАВИЛО: сомневаешься — не ставь. Пустой массив — норма для
  большинства звонков, а не пропуск. Каждый поставленный флаг ОБЯЗАН иметь
  запись в riskEvidence с ДОСЛОВНОЙ цитатой из расшифровки; флаг без
  цитаты при приёме разбора снимается. Артефакты распознавания речи
  (искажённые слова, обрывки, ослышки) — не основание ни для одного флага.
  Коды и критерии:
  promise — «Необоснованное обещание клиенту»: менеджер пообещал то, чего
    продукт или компания не делает, либо что вне его полномочий —
    несуществующую функцию, скидку или условие вне стандартных,
    необеспеченные сроки. НЕ флаг: стандартные действия (демо-доступ, КП,
    акция, перезвонить, прислать материалы), обещание уточнить, «посмотрим».
  conflict — «Конфликт / грубость»: ТОЛЬКО реплики МЕНЕДЖЕРА —
    раздражение, грубость, переход на личности, спор на повышенных тонах,
    угрозы. Грубость или резкость клиента — не этот флаг.
  compliance — «Нарушение регламента»: только если в материалах портала
    есть регламент или скрипт И нарушение явное — не представился, не
    назвал компанию, обсуждал запрещённое, раскрыл чужие данные. Без
    материалов регламента — не ставить.
  client_negative — «Сильный негатив клиента»: клиент ПРЯМО выражает
    возмущение компанией, менеджером или продуктом, грозит жалобой, в
    резкой форме требует прекратить звонки, бросает трубку с резкими
    словами. Спокойный отказ, «не интересно», «не сейчас» — НЕ флаг.
  door_closed — «После отказа не оставил дверь открытой»: клиент отказал
    в любой форме (не сейчас, уже есть другая система, нет бюджета, не
    интересно), а менеджер завершил разговор, не договорившись о будущем —
    ни разрешения вернуться (срок, повод, новое предложение: AI-помощник,
    пакет для бухгалтерии, спецсервис, мероприятие), ни альтернативы
    (пробный доступ, материалы, приглашение). Скрипт любой, важен смысл:
    после отказа мы продолжаем работать с клиентом, а не «ладно, до
    свидания». НЕ ставить: недозвон, секретарь, ошибочный номер, отказ с
    агрессией (это client_negative), клиент сам предложил вернуться позже и
    менеджер это зафиксировал.
- riskEvidence — по одной записи на каждый поставленный флаг: flag — код
  флага; quote — дословная реплика из расшифровки (не пересказ); speaker —
  чья реплика: manager (обещание, конфликт, регламент, закрытая дверь)
  или client (негатив клиента); ${QUOTE_TIMECODE_SPEC}.
  Флагов нет — пустой массив.`;
