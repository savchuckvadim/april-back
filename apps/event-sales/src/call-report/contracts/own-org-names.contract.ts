/**
 * НАЗВАНИЯ НАШИХ ОРГАНИЗАЦИЙ в промптах разбора.
 *
 * Прод-случай alfacentr (08.09.2026): модель написала «менеджер
 * представляется через стороннюю организацию „Альфа-центр“, что создаёт
 * путаницу и дистанцию от основного бренда» и снизила за это оценку. Но
 * «Альфа-центр» — это и есть компания-клиент портала. Все клиенты продукта
 * — партнёры Гаранта и представляются по-разному: у одного портала это
 * «Альфа-центр», «Апрель» и домен почты alfasibir.
 *
 * Промпт знает только «Гарант» (он зашит в рубрику как продукт), поэтому
 * любое партнёрское имя читалось как ЧУЖОЙ бренд. Настройка портала
 * `ownOrgNames` закрывает эту дыру: список уходит в паспорт звонка и в
 * промпты явной формулировкой «это МЫ, снижать оценку за это нельзя».
 *
 * Пустой список — прежнее поведение: функции возвращают пустую строку и
 * в промпте не появляется ни одной лишней инструкции.
 */

/** Потолок имён в промпте: длинный список сам по себе сбивает модель. */
const MAX_NAMES_IN_PROMPT = 20;

/**
 * Чистый список имён для промпта: без пустых, без дублей (регистр не
 * важен), с потолком длины. Настройка приходит из БД, где могло лечь что
 * угодно, — промпт обязан быть предсказуемым.
 */
export function normalizeOwnOrgNames(
    names: readonly string[] | null | undefined,
): string[] {
    const seen = new Set<string>();
    const result: string[] = [];
    for (const raw of names ?? []) {
        const name = String(raw ?? '').trim();
        if (name.length < 2) continue;
        const key = name.toLowerCase();
        if (seen.has(key)) continue;
        seen.add(key);
        result.push(name);
        if (result.length >= MAX_NAMES_IN_PROMPT) break;
    }
    return result;
}

/** Перечисление имён в кавычках: «Альфа-центр», «Апрель». */
function renderNameList(names: readonly string[]): string {
    return names.map(name => `«${name}»`).join(', ');
}

/**
 * Блок для промптов разбора (фокус-вызовы, синтез, цельный разбор,
 * проверка по регламенту). Формулировка ЯВНАЯ — модель не должна
 * догадываться: представление одним из этих имён норма, снижать оценку
 * за «стороннюю организацию» запрещено.
 *
 * Пустой список — пустая строка (промпт не меняется).
 */
export function renderOwnOrgNamesBlock(
    names: readonly string[] | null | undefined,
): string {
    const list = normalizeOwnOrgNames(names);
    if (!list.length) return '';
    return (
        `\n\nНАШИ СОБСТВЕННЫЕ НАЗВАНИЯ (обязательно к учёту)\n` +
        `Компания менеджера работает под именами: ${renderNameList(list)}. ` +
        `Это МЫ — партнёр «Гаранта», а не сторонняя организация и не ` +
        `посредник.\n` +
        `- Менеджер, который представился любым из этих имён, назвал СВОЮ ` +
        `компанию. Это НОРМА.\n` +
        `- ЗАПРЕЩЕНО писать, что менеджер представляется «через стороннюю ` +
        `организацию», «путает бренды», «создаёт дистанцию от основного ` +
        `бренда», и ЗАПРЕЩЕНО снижать за это оценку или заносить это в ` +
        `нарушения, риски и рекомендации.\n` +
        `- Имя клиента и имя нашей компании не путай: клиент — тот, КОМУ ` +
        `звонят (он назван в контексте CRM).`
    );
}

/**
 * Короткая подсказка классификатору типа звонка: имя из списка в реплике
 * менеджера — это представление НАШЕЙ компании, а не разговор о чужой
 * организации (иначе холодный выход читается как «звонок про партнёра»).
 */
export function renderOwnOrgNamesHint(
    names: readonly string[] | null | undefined,
): string {
    const list = normalizeOwnOrgNames(names);
    if (!list.length) return '';
    return (
        `наша компания на этом портале называется ${renderNameList(list)} — ` +
        `менеджер, назвавший одно из этих имён, представляет СЕБЯ, а не ` +
        `говорит о сторонней организации`
    );
}
