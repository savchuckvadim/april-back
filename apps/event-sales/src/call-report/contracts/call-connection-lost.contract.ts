/**
 * Общее правило «обрыв связи» (focus-v3.5 / v3.6, 26.11.2026): звонок
 * оборвался из-за связи посреди разговора — модель не должна читать это как
 * поступок менеджера («бросил трубку», «не завершил разговор»), снижать за
 * это оценку закрытия или ставить сигнал руководителю.
 *
 * Правило одно на все задания, где модель оценивает конец разговора или
 * ставит исход: оно подключается один раз к общему ядру правил
 * (DEEP_ANALYSIS_RULES_WITH_CONNECTION_LOST в call-deep-analysis.contract) и
 * отдельно — к догону признаков. Тексты исхода и сбоя «связь прервалась» —
 * в call-report-facts.contract. Определение типа звонка и распознавание речи
 * правилом не затрагиваются.
 */
export const CALL_CONNECTION_LOST_RULE = `ОБРЫВ СВЯЗИ. Если запись кончается на полуслове, посреди фразы или темы, без
прощания и без слов о завершении — это обрыв связи, а не поступок менеджера.
Телефонная связь обрывается постоянно; менеджер трубку почти никогда не
бросает. Поэтому:
- не пиши, что менеджер «бросил трубку», «оборвал разговор», «прервал
  звонок», «не попрощался» или «не завершил разговор»: так можно написать,
  только если в тексте есть прямые слова об этом (менеджер сам сказал, что
  кладёт трубку, или клиент сказал «вы бросили трубку»);
- всё, до чего разговор не успел дойти из-за обрыва (итог, резюме
  договорённостей, следующий шаг, работа с отказом, прощание), — недостижимый
  этап: не оценивай его, не снижай за него оценку и не давай по нему советов;
- то, что прозвучало до обрыва, оценивай как обычно;
- сомневаешься, оборвалась связь или разговор закончили, — считай, что
  оборвалась связь.`;
