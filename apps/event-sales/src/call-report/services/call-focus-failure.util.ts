import { isTransientLlmError } from '@lib/llm-gateway';
import type { AgentCallAnalysisDto } from '../../agent-gate/dto/agent-analysis-request.dto';

/**
 * Итог фокус-разбора для процессора: разбор или причина, почему его нет
 * (11.11.2026). Вынесено из CallFocusAnalysisService по лимиту файла.
 */
export interface CallFocusOutcome {
    /**
     * Собранный разбор; null — не собрался: выжило меньше двух проходов,
     * пустой транскрипт или сбой сборки.
     */
    analysis: AgentCallAnalysisDto | null;
    /**
     * Разбора нет, потому что проходы оборвались на поставщике модели
     * (таймаут, 429, 5xx, сеть, отказали все поставщики) — цельную
     * страховку звать бесполезно. false — разбор есть или причина другая.
     */
    providerFailure: boolean;
}

/**
 * Провал фокус-разбора — сбой поставщика, если хоть один из сорвавшихся
 * фокус-проходов оборвался по временной причине (isTransientLlmError:
 * таймаут, 5xx, 429, 408, сеть; у сводной ошибки шлюза — временный сбой
 * или пауза ОСНОВНОГО поставщика: 429 запасного Groq при негодном ответе
 * VibeCode сбоем поставщика не считается). Проходы идут к модели одновременно: раз один не дождался
 * ответа, поставщик сейчас не справляется, и цельный разбор — самый
 * тяжёлый запрос — почти наверняка оборвётся так же. Негодный ответ модели
 * (невалидный JSON, схема не прошла, 400) — не сбой поставщика.
 *
 * `passErrors` — ошибки только трёх фокус-проходов: от них зависит, собран
 * ли разбор; проход «методика» на это не влияет.
 */
export function isFocusProviderFailure(
    passErrors: readonly unknown[],
): boolean {
    return passErrors.some(error => isTransientLlmError(error));
}
