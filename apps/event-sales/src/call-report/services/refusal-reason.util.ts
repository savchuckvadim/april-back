/**
 * СОДЕРЖАТЕЛЬНОСТЬ ПРИЧИНЫ ОТКАЗА.
 *
 * Прод-случай alfacentr (08.09.2026): менеджер закрыл сделку финалом
 * отказа с комментарием «08.09 отказ», а поле «ОП Причина Отказа» осталось
 * пустым. Без причин отказа не работает ни разбор возражений, ни аналитика
 * утечек, поэтому «отчёт» из даты и слова «отказ» обязан считаться ПУСТЫМ.
 *
 * Порог задан НЕ длиной строки (владелец, §3 плана прод-фиксов), а
 * наличием смысла: из текста вычищаются даты, числа и служебные слова
 * самого отказа — если после этого не осталось ни одного содержательного
 * слова, причина не зафиксирована.
 *
 * Значение ВЫПАДАЮЩЕГО СПИСКА проверять этой функцией не нужно: элемент
 * справочника («Нет денег», «Конкуренты - цена») уже есть зафиксированная
 * причина по определению — там проверяется только факт заполнения.
 */

/** Минимальная длина содержательного слова (короче — предлог/частица). */
const MEANINGFUL_WORD_MIN_LENGTH = 4;

/**
 * Слова, которые сами по себе причиной НЕ являются: они называют факт
 * отказа, а не его причину. Список намеренно короткий — всё остальное
 * («дорого», «денег», «конкурент») содержательно.
 */
const NON_REASON_WORDS = new Set([
    'отказ',
    'отказы',
    'отказался',
    'отказалась',
    'отказались',
    'отказано',
    'отказ.',
    'клиент',
    'клиента',
    'компания',
    'звонок',
    'звонил',
    'звонила',
    'сделка',
    'нет',
    'без',
    'все',
    'всё',
    'пока',
    'потом',
    'спасибо',
    'свидания',
]);

/** Даты и время в любом обычном виде: 08.09, 08.09.2026, 8/9, 12:30. */
const DATE_LIKE = /\d{1,4}[.\-/:]\d{1,4}([.\-/:]\d{1,4})?/g;

/**
 * Есть ли в тексте зафиксированная причина отказа.
 *
 * Пусто, только дата, только слово «отказ» и их сочетания → false.
 */
export function isMeaningfulRefusalReason(
    value: string | null | undefined,
): boolean {
    const raw = (value ?? '').trim();
    if (!raw) return false;
    const words = raw
        .replace(DATE_LIKE, ' ')
        .replace(/[^\p{L}\p{N}]+/gu, ' ')
        .toLowerCase()
        .split(' ')
        .filter(Boolean);
    return words.some(
        word =>
            word.length >= MEANINGFUL_WORD_MIN_LENGTH &&
            !NON_REASON_WORDS.has(word) &&
            // Чистое число (год, сумма без пояснения) причиной не является.
            !/^\d+$/.test(word),
    );
}

/** Что именно нашли в полях менеджера — для поля смарта и лога. */
export interface ManagerRefusalReason {
    /** Текст причины из полей/записей; null — не нашли. */
    text: string | null;
    /** Причина зафиксирована: заполнен справочник или содержательный текст. */
    recorded: boolean;
    /** Откуда взято (для объяснения сверки). */
    source: 'deal_field' | 'deal_comment' | 'list_record' | null;
    /**
     * Поля причины отказа заведены на портале. false — портал без нужных
     * полей: сверять нечего, расхождения НЕ ставим (штатная деградация).
     */
    fieldsConfigured: boolean;
}

/** Пусто-результат: полей на портале нет либо читать было нечего. */
export const NO_MANAGER_REFUSAL_REASON: ManagerRefusalReason = {
    text: null,
    recorded: false,
    source: null,
    fieldsConfigured: false,
};

/** Явный текст в поле смарта, когда причины в карточке нет. */
export const MANAGER_REFUSAL_REASON_MISSING =
    'Причина отказа не зафиксирована: поле «ОП Причина Отказа» сделки и ' +
    'записи «ОП KPI»/«ОП История» пусты.';

/** Явный текст, когда поля причины отказа на портале не заведены. */
export const MANAGER_REFUSAL_FIELDS_MISSING =
    'Поля причины отказа на портале не заведены — сверять не с чем.';

/**
 * Объяснение сверки для карточки: коротко и по делу, без обвинений —
 * система восполняет данные, а не наказывает менеджера.
 */
export function renderRefusalMismatchNote(
    aiReason: string | null,
    stageTitle: string,
): string {
    const head =
        `Сделка закрыта финалом «${stageTitle}», но причина отказа в ` +
        `карточке и в записях отчётности не заполнена.`;
    return aiReason
        ? `${head} В разговоре причина прозвучала: ${aiReason}`
        : `${head} В разговоре причина тоже не прозвучала — уточните у менеджера.`;
}
