/**
 * Константы сервиса «длинный разговор по частям» (этап 4в): сколько запросов
 * к модели идёт одновременно, сколько попыток на запрос, когда длинный путь
 * считается неудавшимся и как долго живёт кэш ответов. Числа 4а (порог,
 * размер части) — в long-call.const.ts, они же — умолчания настроек вендора.
 *
 * Чистые константы: без DI, Bitrix и Prisma.
 */

/** Запросов конспектов частей одновременно, не больше. */
export const LONG_CALL_PART_CONCURRENCY = 3;

/** Запросов на одну часть (и на сводку), не больше: первый и один повтор. */
export const LONG_CALL_MAX_ATTEMPTS = 2;

/**
 * Частей меньше стольких — длинный путь не нужен: расшифровка уложилась в одну
 * часть, конспект и сводка ничего не сократят, разбор идёт по полной расшифровке.
 */
export const LONG_CALL_MIN_PARTS = 2;

/**
 * Без конспекта осталось больше такой доли частей — длинный путь не удался,
 * разбор идёт по полной расшифровке, как раньше.
 */
export const LONG_CALL_MAX_MISSING_SHARE = 1 / 2;

/** Срок жизни ответа модели в кэше, секунд (24 часа). */
export const LONG_CALL_CACHE_TTL_SEC = 24 * 60 * 60;

/** Начало ключа кэша; версия — на случай смены формата записи. */
export const LONG_CALL_CACHE_KEY_PREFIX = 'event-sales:long-call:v1';

/** Что разделяет поля, из которых считается ключ кэша (ни в тексте, ни в имени его нет). */
export const LONG_CALL_CACHE_KEY_SEPARATOR = '\u0000';

/** Знаков после запятой у времени подготовки в журнале, секунд. */
export const LONG_CALL_LOG_SECONDS_DIGITS = 1;

/** Миллисекунд в секунде. */
export const MS_IN_SECOND = 1_000;
