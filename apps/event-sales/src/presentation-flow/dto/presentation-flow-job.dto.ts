import { PresentationOutcome } from '../lib/presentation-outcome';
import { PresentationSurveySnapshot } from '../lib/presentation-survey-snapshot';
import { QuestionnaireSmartAnswer } from '../../shared/questionnaire-answers';

/**
 * Джоб сайд-очереди презентаций (EVENT_SALES_PRESENTATION_FLOW).
 *
 * Основной event-report кладёт сюда МИНИМАЛЬНЫЙ снимок контекста и отвечает
 * «предварительно готово» — элемент смарта «Презентации» доезжает асинхронно
 * и не удлиняет основной flow (та же схема, что у ЗПР).
 *
 * Сделки «ОП Презентации» этот джоб НЕ трогает: они двигаются основным flow
 * как раньше, смарт живёт параллельно.
 */
export interface PresentationFlowJobData {
    domain: string;
    /** operationId основного отчёта — для трассировки в логах. */
    operationId?: string;
    /**
     * Сокет клиента, отправившего отчёт: по завершении джоба туда уходит
     * `presentation-flow:done`. Точечная доставка по socketId, НЕ по userId —
     * id юзера уникален только в рамках портала.
     */
    socketId?: string;
    /**
     * `plan` — менеджер запланировал презентацию (создать элемент в
     * «Запланирована»); `report` — отчитался по презентации (закрыть или
     * перенести элемент; не нашли — создать спонтанный сразу с исходом).
     */
    kind: 'plan' | 'report';
    /** Исход отчёта (kind='report'); для плана не заполняется. */
    outcome: PresentationOutcome | null;
    /** Встреча состоялась — разводит отказ на «отказ» и «не состоялась». */
    isResult: boolean;
    /**
     * Презентация была СПОНТАННОЙ (незапланированной): плана не было, либо
     * отчёт пришёл не по презентационной задаче. Такой отчёт не закрывает
     * чужой открытый элемент — он фиксирует НОВУЮ презентацию сразу фактом
     * (ровно как unplanned pres-сделка в основном flow).
     */
    isSpontaneous: boolean;
    /**
     * Задача, ПО КОТОРОЙ отчитались: элемент смарта привязывается к ней в
     * UF_CRM_TASK (`T{hex}_{id}`) по завершении report-джоба (зеркало
     * zpr-flow). Задача, СОЗДАННАЯ этим же отчётом, едет отдельным полем
     * `planTaskId` — здесь всегда та, что закрывается.
     */
    taskId?: number | null;
    /**
     * Задача, СОЗДАННАЯ этим отчётом (план). Реальный числовой id читается из
     * ответа того же батча (`$result[add_task]` уже выполнен на момент постановки
     * джоба), поэтому доступен без единого лишнего запроса к Битриксу. Элемент
     * плана привязывается к ней в UF_CRM_TASK значением `T{hex}_{id}`.
     */
    planTaskId?: number | null;
    /**
     * Привязки UF_CRM_TASK задачи, ПО КОТОРОЙ отчитываются (сырьё из
     * currentTask фронта). Среди них лежит динамическая привязка `T{hex}_{id}`
     * — ЕДИНСТВЕННЫЙ точный указатель на элемент смарта этой задачи:
     * звонков клиенту может быть запланировано
     * несколько, и эвристика «свежий открытый элемент клиента» закрывает
     * не тот (инцидент 31.08 — вместо элемента из задачи создался
     * спонтанный дубль). Flow парсит отсюда id своего смарта и закрывает
     * именно его; поле пустое — честный фолбэк на эвристику.
     */
    taskCrmBindings?: string[];
    /** id базовой сделки; null — сделка создаётся этим же отчётом/лид-only. */
    baseDealId: number | null;
    /** Сделка воронки «ОП Презентации» — зеркальная ссылка на элемент. */
    presDealId: number | null;
    /**
     * ТМЦ-сделка (воронка `tmc_base`), из которой пришла заявка на
     * презентацию. Резолвится контекстом отчёта (привязки задачи или
     * обратная ссылка UF_CRM_TO_PRESENTATION_SALES) — элемент забирает её
     * себе полем PRES_TMC_DEAL, чтобы связь пережила отказ от pres-сделок.
     */
    tmcDealId: number | null;
    companyId: number | null;
    leadId: number | null;
    contactId: number | null;
    /** Кто проводит/провёл презентацию. */
    responsibleId: number;
    /** Кто назначил презентацию (лидоген ≠ менеджер). */
    planResponsibleId: number;
    /** Дедлайн плана, DD.MM.YYYY HH:mm:ss локали портала. */
    planDeadline: string | null;
    planName: string | null;
    /** Комментарий менеджера на момент планирования. */
    planComment: string | null;
    /** Комментарий отчёта (kind='report'). */
    reportComment: string | null;
    /**
     * Причина отказа, которую менеджер ДЕЙСТВИТЕЛЬНО выбрал (суффикс
     * справочника: `notime`, `c_price`, …). Контекст отдаёт её только на
     * финальном отказе типа «Отказ» — на остальных отчётах здесь null, и
     * элемент остаётся без причины (см. EventReportContext.failReasonCode).
     */
    failReasonCode: string | null;
    /** Снимок анкеты «5К»/«Хвост» на момент отчёта (kind='report'). */
    survey: PresentationSurveySnapshot;
    /**
     * Ответы ПОРТАЛЬНОЙ анкеты (каталог админки), адресованные полям
     * элемента. Рядом с `survey`, а не вместо: у них разные ключи и разное
     * происхождение — `survey` адресуется кодом НАШЕГО реестра полей и
     * снят с уже загруженных лида и сделки, `answers` адресуется UF-именем
     * ПРОИЗВОЛЬНОГО поля портала и надиктован менеджером сейчас. Слияние
     * заставило бы один из ключей врать.
     *
     * Поле опциональное: в очереди во время деплоя лежат джобы старой
     * формы (ровно так же читается `job.survey ?? {}`).
     */
    answers?: QuestionnaireSmartAnswer[];
}
