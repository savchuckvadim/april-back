import { ApiProperty } from '@nestjs/swagger';

/**
 * Ответ чтения настроек для фрейма: значения ПЛОСКО (ключ схемы →
 * значение) плюс поле-сосед `storedKeys`.
 *
 * Почему плоско, а не `{ values, storedKeys }`: форму ответа менять
 * нельзя — фреймы, уехавшие на порталы раньше, читают ключи прямо с
 * верхнего уровня. Новое поле старый фрейм просто не заметит (он идёт по
 * своему реестру ключей), а новый — применит только то, что в списке.
 *
 * Коллизия имени с ключом реестра исключена сторожевым тестом
 * (__tests__/portal-app-settings.schema.spec.ts): ключа `storedKeys` в
 * схеме нет и быть не должно.
 */
export class AppSettingsResolvedDto {
    @ApiProperty({
        description:
            'Ключи (camelCase, как в реестре), значения которых РЕАЛЬНО ' +
            'заданы на портале. Остальные ключи ответа — дефолты кода: ' +
            'фронт со своими дефолтами (доменный конфиг) вправе их не ' +
            'применять. Записи настроек у портала нет — список пуст.',
        type: [String],
        example: ['withNoPlan', 'taskGroupId'],
    })
    storedKeys: string[];

    /** Значения настроек: ключ схемы (camelCase) → значение. */
    [key: string]: boolean | number | string | string[];
}
