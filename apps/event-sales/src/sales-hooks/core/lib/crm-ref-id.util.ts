/**
 * ID сущности из параметра вебхука, как его подставляет Битрикс.
 *
 * Параметр бизнес-процесса типа «Привязка к CRM» отдаёт значение с
 * префиксом типа — `D_42423`, `CO_91429`, `C_5`, `L_7`, иногда в скобках.
 * Голое число тоже бывает. Хук ждёт число: без разбора `D_42423` не
 * проходил валидацию, Битрикс получал 400, и БП «Отдать работу» молча не
 * срабатывал (garant, 01.10.2026).
 *
 * Не разобралось — значение возвращается как есть, и валидатор DTO
 * честно откажет с понятной ошибкой.
 */
export const crmRefId = (raw: unknown): unknown => {
    if (typeof raw === 'number') return raw;
    if (typeof raw !== 'string') return raw;
    const match = raw.trim().match(/^\[?\s*(?:[A-Z]{1,3}_)?(\d+)\s*\]?$/i);
    return match ? Number(match[1]) : raw;
};
