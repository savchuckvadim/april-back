import { SmartKpiRowRef } from '../../shared/side-flow';
import { ZprSurveySnapshot } from '../lib/zpr-survey-snapshot';
import { QuestionnaireSmartAnswer } from '../../shared/questionnaire-answers';

/**
 * Джоб сайд-очереди ЗПР (EVENT_SALES_ZPR_FLOW).
 *
 * Основной event-report кладёт сюда МИНИМАЛЬНЫЙ снимок контекста и отвечает
 * «предварительно готово» — элемент смарта «Звонки По решению» доезжает
 * асинхронно и не удлиняет основной flow (решение владельца, 2508).
 */
export interface ZprFlowJobData {
    domain: string;
    /** operationId основного отчёта — для трассировки в логах. */
    operationId?: string;
    /**
     * Сокет клиента, отправившего отчёт: по завершении джоба туда уходит
     * `zpr-flow:done`. Точечная доставка по socketId, НЕ по userId —
     * id юзера уникален только в рамках портала.
     */
    socketId?: string;
    /**
     * `plan` — менеджер запланировал ЗПР (создать элемент в «Запланирован»);
     * `report` — отчитался по ЗПР-задаче (закрыть элемент; не нашли —
     * создать спонтанный сразу с исходом).
     */
    kind: 'plan' | 'report';
    /**
     * Перенос (отчёт «Не очень» + та же задача на новую дату): элемент НЕ
     * закрывается — двигается в «Ожидание» с инкрементом счётчика переносов.
     * Без этого флага перенос закрывал бы элемент «Не состоялся», а план
     * той же задачи создавал бы второй открытый (находка ревью).
     */
    isMove?: boolean;
    /**
     * Задача, ПО КОТОРОЙ отчитались (kind='report'/перенос): по завершении
     * джоба элемент смарта привязывается к ней в UF_CRM_TASK значением
     * `T{hex}_{id}` — чтобы сущности легко находились из задачи и обратно
     * (вопрос владельца 25.08). Задача, СОЗДАННАЯ этим же отчётом, едет
     * отдельным полем `planTaskId` — здесь всегда та, что закрывается.
     */
    taskId?: number | null;
    /**
     * Задача, СОЗДАННАЯ этим отчётом (план). Реальный числовой id читается из
     * ответа того же батча (`$result[add_task]` уже выполнен на момент постановки
     * джоба), поэтому доступен без единого лишнего запроса к Битриксу. Элемент
     * плана привязывается к ней в UF_CRM_TASK значением `T{hex}_{id}`.
     */
    planTaskId?: number | null;
    /**
     * Привязки UF_CRM_TASK задачи, ПО КОТОРОЙ отчитываются (сырьё из
     * currentTask фронта). Среди них лежит динамическая привязка `T{hex}_{id}`
     * — ЕДИНСТВЕННЫЙ точный указатель на элемент смарта этой задачи:
     * звонков клиенту может быть запланировано
     * несколько, и эвристика «свежий открытый элемент клиента» закрывает
     * не тот (инцидент 31.08 — вместо элемента из задачи создался
     * спонтанный дубль). Flow парсит отсюда id своего смарта и закрывает
     * именно его; поле пустое — честный фолбэк на эвристику.
     */
    taskCrmBindings?: string[];
    /**
     * Строки KPI/History-списков ЭТОГО отчёта (id из ответа батча) — джоб
     * дописывает в их multiple-crm-поле ссылку на свой элемент
     * (T{hex}_{id}): плановый элемент в план-строки, отчётный — в
     * отчётные (решение владельца 31.08). Пусто — строки не создавались
     * либо на списке нет crm-поля.
     */
    kpiRows?: SmartKpiRowRef[];
    /** id базовой сделки; null — сделка создаётся этим же отчётом/лид-only. */
    baseDealId: number | null;
    presDealId: number | null;
    companyId: number | null;
    leadId: number | null;
    contactId: number | null;
    responsibleId: number;
    /** Дедлайн плана, DD.MM.YYYY HH:mm:ss локали портала. */
    planDeadline: string | null;
    planName: string | null;
    /** Комментарий менеджера на момент планирования. */
    planComment: string | null;
    /** Комментарий отчёта (kind='report'). */
    reportComment: string | null;
    /** Разговор состоялся (kind='report'). */
    isResult: boolean;
    /**
     * Финал клиента, объявленный ЭТИМ отчётом: отказ (в том числе «не ЦА»)
     * закрывает звонок стадией «Состоялся: отказ». Без этого признака
     * «дозвонились и получили отказ» лежало бы в успехах рядом с
     * «дозвонились и работаем» (правило владельца 26.08).
     */
    isFail?: boolean;
    /**
     * Снимок анкеты по коду поля смарта — зеркало презентационного
     * `survey`. Состав переноса (какие поля клиента едут в элемент ЗПР)
     * ещё не назван владельцем, поэтому сегодня поле не заполняется; сам
     * поток его уже принимает и раскладывает.
     */
    survey?: ZprSurveySnapshot;
    /**
     * Ответы ПОРТАЛЬНОЙ анкеты, адресованные полям элемента. Рядом с
     * `survey`, а не вместо (см. presentation-flow-job.dto): у ключей
     * разное происхождение — код нашего реестра против UF-имени
     * произвольного поля портала.
     */
    answers?: QuestionnaireSmartAnswer[];
}
