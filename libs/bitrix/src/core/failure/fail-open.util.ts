/**
 * Подпись тревог и журнал сбоев — вспомогательная работа на пути ошибки
 * вызова Битрикса. Её собственный сбой не должен менять исход вызова:
 * повтор, исключение вызывающему, результат пачки. Поэтому — запасное
 * значение вместо исключения.
 */
export function failOpen<T>(work: () => T, fallback: T): T {
    try {
        return work();
    } catch {
        return fallback;
    }
}
