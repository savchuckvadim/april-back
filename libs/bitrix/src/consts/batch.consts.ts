/**
 * ЭКРАНИРОВАНИЕ — СВОЙСТВО ТРАНСПОРТА, А НЕ ТЕКСТА. Прочти это правило до
 * того, как выберешь функцию ниже: непоследовательное применение уже стоило
 * порталу испорченных значений (два писателя одного поля разошлись).
 *
 * Функции этого файла готовят текст ровно для ОДНОГО транспорта — того, что
 * склеивает query-строку `cmd` РУКАМИ и значения в неё вклеивает СЫРЫМИ
 * (`BatchApiService.dictToQueryString`: экранируется только `=` в КЛЮЧЕ, см.
 * `libs/bitrix/src/core/base/batch-api.service.ts`). Битрикс потом
 * url-декодирует эту строку ОДИН раз — поэтому текст обязан приехать сюда
 * уже в query-виде.
 *
 * Из этого следуют два правила, нарушать которые нельзя:
 *
 *  1. ОДНО ЗНАЧЕНИЕ — ОДИН СПОСОБ. Если поле пишут несколько писателей
 *     (основной батч и волна лид-синка, payload и перенос с лида), все они
 *     обязаны звать ОДНУ И ТУ ЖЕ функцию. Слабый писатель, идущий последним,
 *     перезатирает сильного — и в карточку ложится обрубок.
 *  2. ТРАНСПОРТ, КОДИРУЮЩИЙ САМ, обязан это экранирование СНЯТЬ. Браузерное
 *     зеркало потока отдаёт команды b24jssdk, а тот строит `cmd` через
 *     `qs.stringify` с `encode: true` — без снятия `%` уехал бы как `%25`, и
 *     в поле легло бы литеральное `%0A` вместо переноса. Снятие живёт в
 *     адаптере транспорта (`packages/event-sales-flow/src/adapters/browser/
 *     bitrix-flow-transport.ts`), а НЕ здесь: текст один и тот же, разные —
 *     провода.
 */

/**
 * Символ переноса строки для текста, уходящего batch-командой.
 *
 * Значения batch-команд вклеиваются в query-строку `cmd` как есть и
 * url-декодируются на стороне Битрикс: сырой `\n` при этом теряется
 * (в полях карточки он доезжает подчёркиванием), а `%0A` декодируется
 * в настоящий перенос строки.
 */
export const BATCH_LINE_BREAK_SYMBOL = '%0A';

/**
 * Готовит многострочный текст к отправке batch-командой: все виды
 * переносов (`\r\n`, `\r`, `\n`) заменяются на
 * {@link BATCH_LINE_BREAK_SYMBOL}. Обязательно для пользовательского
 * текста (комментарии менеджеров) — иначе переносы в карточке
 * превращаются в подчёркивания.
 *
 * СЛАБЫЙ вариант: `&`, `+` и `%` он не трогает. Годится там, где формат
 * значения задаёт КОД (склейки истории, шапки комментариев), и НЕ годится
 * для свободного текста менеджера, уезжающего одним значением команды —
 * там только {@link toBatchSafeText}.
 */
export const toBatchText = (text: string): string =>
    text.replace(/\r\n|\r|\n/g, BATCH_LINE_BREAK_SYMBOL);

/**
 * Значение ОДНОЙ записи МНОЖЕСТВЕННОГО UF-поля (op_mhistory, ленты
 * комментариев смартов): все переносы схлопываются в видимый разделитель.
 *
 * ВАЖНО, почему не BATCH_LINE_BREAK_SYMBOL: батч уходит JSON-телом
 * ({halt, cmd}), Битрикс декодирует внутреннюю query-строку один раз, и
 * `%0A` превращается в НАСТОЯЩИЙ `\n` в сохранённом значении — а грид
 * множественного поля рисует внутренние переносы ПОДЧЁРКИВАНИЕМ
 * (инцидент 31.08: «ОП История» на компании и сделках вся в `_`).
 * `%0A`-приём остаётся верным для таймлайна и задач — их рендеры понимают
 * переносы; для записей multiple-полей единственный честный вариант —
 * одна строка с разделителем.
 */
export const toMultiFieldEntryText = (
    text: string,
    separator = ' — ',
): string =>
    text
        .replace(/%0A/g, separator)
        .replace(/(?:\r\n|\r|\n)+/g, separator)
        .replace(/\s+/g, ' ')
        .trim();

/**
 * Строгий вариант {@link toBatchText} для БОЛЬШИХ текстов, которые целиком
 * уезжают одним значением batch-команды (DESCRIPTION задачи и т.п.).
 *
 * Кроме переносов экранируются ещё три символа, которые ломают разбор
 * `cmd`-строки на стороне Битрикс:
 *  - `&` делит query-строку на параметры — всё после него уехало бы отдельным
 *    (мусорным) полем, а текст оборвался бы на середине («Иванов & Партнёры»);
 *  - `+` в query-строке декодируется ПРОБЕЛОМ — телефоны «+7 900…» доезжали
 *    до карточки как « 7 900…»; экранируется ПОСЛЕ `%` (иначе `%` из `%2B`
 *    удвоился бы) и это безопасно относительно `&` (`%2B` его не содержит);
 *  - `%` сам является началом escape-последовательности: «скидка 50%0A…»
 *    превратилась бы в «скидка 50» + перенос, поэтому экранируется ПЕРВЫМ.
 *
 * {@link toBatchText} намеренно оставлен как есть: его поведение зашито в
 * форматы истории и комментариев карточек.
 *
 * ЗОНА ОБЯЗАТЕЛЬНОГО ПРИМЕНЕНИЯ — СВОБОДНЫЙ ТЕКСТ МЕНЕДЖЕРА в batch-поле:
 * ответы анкеты презентации (5К/Хвост/Разговор) на любой цели и любым
 * писателем, описания и комментарии задач. Перенос такого значения с одной
 * сущности на другую — тоже запись в batch-поле: копия обязана ехать той же
 * функцией, что и оригинал (правило 1 в шапке файла).
 */
export const toBatchSafeText = (text: string): string =>
    text
        .replace(/%/g, '%25')
        .replace(/\+/g, '%2B')
        .replace(/&/g, '%26')
        .replace(/\r\n|\r|\n/g, BATCH_LINE_BREAK_SYMBOL);
