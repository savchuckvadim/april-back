const ROLE_LABEL: Record<SupportAuthorRole, string> = {
    client: 'Клиент',
    staff: 'Сотрудник April',
    other: 'Система или бот линии',
};

const moscowTime = new Intl.DateTimeFormat('ru-RU', {
    timeZone: 'Europe/Moscow',
    day: '2-digit',
    month: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
});

function clip(text: string, max: number): string {
    const value = text.replace(/\s+/gu, ' ').trim();
    return value.length > max ? `${value.slice(0, max - 1)}…` : value;
}

function formatMessage(message: SupportMessage): string {
    const author = message.authorName ? ` (${message.authorName})` : '';
    return `[${moscowTime.format(new Date(message.at))}] ${ROLE_LABEL[message.role]}${author}: ${clip(message.text, MESSAGE_MAX) || '(без текста: файл или вложение)'}`;
}

function formatErrors(
    errors: SupportClientErrors | null,
    portal: string | null,
): string[] {
    if (!portal) {
        return ['Портал клиента неизвестен — журнал ошибок не смотрели.'];
    }
    if (!errors) {
        return [`Журнал ошибок по порталу ${portal} сейчас недоступен.`];
    }
    const lines = [
        `Ошибки наших приложений на портале ${portal} за ${errors.summary.hours} ч:`,
    ];
    if (!errors.recent.length) {
        lines.push('- ошибок нет');
    }
    for (const conclusion of errors.summary.conclusions) {
        lines.push(`- вывод: ${conclusion}`);
    }
    for (const row of errors.recent.slice(0, ERRORS_MAX)) {
        lines.push(
            `- [${moscowTime.format(new Date(row.at))}] ${row.app}: ${clip(row.message, ERROR_TEXT_MAX)}`,
        );
    }
    return lines;
}

/** Переписка и контекст клиента — пользовательская часть запроса. */
export function buildAnalysisContent(input: {
    view: SupportChatView;
    errors: SupportClientErrors | null;
}): string {
    const { view } = input;
    const portal = view.client?.portal ?? null;
    const client = view.client
        ? `${view.client.name}${portal ? ` (портал ${portal})` : ''}`
        : 'не определён';
    return [
        `Линия поддержки: ${view.domain}, чат №${view.chatId}.`,
        `Клиент: ${client}.`,
        '',
        `Переписка (старые сверху, время московское${view.hasMore ? ', есть более старые сообщения' : ''}):`,
        ...view.messages.map(formatMessage),
        '',
        ...formatErrors(input.errors, portal),
        '',
        'Разбери последнее обращение клиента и подготовь черновик ответа.',
    ].join('\n');
}
