const CONCEPT = `## Кто есть кто

- **Организация (клиент)** — карточка в «Клиентах». У организации может быть несколько порталов Битрикс24.
- **Портал** — привязывается к организации на вкладке портала «Кабинет».
- **Учётная запись** — человек с email и паролем. Связь с порталом — роль:
  - **владелец** — один на портал: раздаёт доступы, подтверждает заявки, может передать права;
  - **участник** — пользуется кабинетом;
  - **заявка** — сотрудник попросил доступ из Битрикс24, прав пока нет.
- **April (суперпользователь админки)** может всё за любого клиента: дать доступ, сменить владельца, выдать ссылку на пароль.

## Как входят

| Где | Как | Что хранится |
|---|---|---|
| Сайт bitrix.april-app.ru | email + пароль | короткий токен (15 мин) — в памяти вкладки; длинный (30 дней) — httpOnly-cookie на api.pbx, меняется при каждом обновлении |
| Приложение April в Битрикс24 | автоматически, по сессии портала | только токен в памяти: cookie во фрейме Битрикса не работают |

Права проверяются по базе на каждом запросе — отзыв доступа действует сразу. Регистрации нет: учётку создаёт April или владелец, пароль человек задаёт сам по одноразовой ссылке.`;

