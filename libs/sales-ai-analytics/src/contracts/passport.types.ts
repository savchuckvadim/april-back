/**
 * Контракты паспорта менеджера и снимка планов руководителя (план Фазы 2,
 * поток 14a; план 4.6 «since без ручного ввода» и 4.9 «цель из плана
 * руководителя»). Объявлены в библиотеке и реэкспортированы
 * `contracts/snapshot.types.ts`: соседние шаги конвейера берут паспорт из
 * шины типом, не импортируя файлы чужого потока.
 *
 * Здесь только форма данных — без DI, Bitrix и Prisma; даты — ISO-строки
 * (payload снапшотов JSON-сериализуем, `Date` внутри запрещены).
 */
import type { AiTenureBand } from '../model/tenure-bands';
import type {
    AiLevelSource,
    AiManagerLevelCode,
} from '../settings/ai-settings.types';

// ---------------------------------------------------------------------------
// Паспорт менеджера (план 4.6 «since без ручного ввода», поток 14a).
// Тип объявлен здесь, а не в приложении, чтобы соседние шаги конвейера
// брали паспорт из шины типом, не импортируя файл чужого потока.
// ---------------------------------------------------------------------------

/**
 * Откуда взята дата начала работы: поле трудоустройства портала, дата
 * регистрации пользователя Bitrix или прокси по первому событию
 * телефонии/отчётности. Руками дату не вводят — источник виден в витрине.
 */
export const AI_PASSPORT_SINCE_SOURCES = [
    'employment',
    'register',
    'proxy',
] as const;
export type AiPassportSinceSource = (typeof AI_PASSPORT_SINCE_SOURCES)[number];

/**
 * Состояние менеджера на дату расчёта: работает, на испытательном сроке,
 * в отсутствии (отпуск/больничный/обучение) или уволен (`ACTIVE = N`).
 * Уволенные и отсутствующие не участвуют в нормах наравне с работающими.
 */
export const AI_MANAGER_STATUSES = [
    'active',
    'probation',
    'absent',
    'left',
] as const;
export type AiManagerStatus = (typeof AI_MANAGER_STATUSES)[number];

/**
 * Паспорт менеджера: собирается автоматически, руками ничего не вводят.
 * Даты — ISO-строки 'YYYY-MM-DD' (payload снапшотов JSON-сериализуем,
 * `Date` внутри запрещены).
 */
export interface ManagerPassport {
    /** Bitrix-id менеджера строкой (как в конверте снапшота). */
    managerId: string;
    /** Дата начала работы; null — не нашли ни одного источника. */
    since: string | null;
    /** Источник даты; null — даты нет (каскад дошёл до конца впустую). */
    sinceSource: AiPassportSinceSource | null;
    status: AiManagerStatus;
    /** Дата последнего события уволенного; null — работает или неизвестна. */
    leftAt: string | null;
    /** Уровень: назначенный руководителем либо подсказанный по стажу. */
    level: AiManagerLevelCode;
    levelSource: AiLevelSource;
    /** Полных месяцев стажа на дату расчёта; null — стаж неизвестен. */
    tenureMonths: number | null;
    /** Полоса стажа для норм; null — стаж неизвестен, норма от портала. */
    tenureBand: AiTenureBand | null;
    /**
     * Отдел продаж на день прогона по структуре портала; null — вне
     * ростера либо раскладка не прочитана. Появилось в Фазе 3 (П3: пара
     * «год назад» помечает смену отдела), поэтому в снапшотах до него
     * поля нет — читатели обязаны переживать undefined.
     */
    departmentId?: number | null;
}

// ---------------------------------------------------------------------------
// Снимок планов руководителя 1-го числа (план 4.9, код реестра
// `plan_snapshot_history`; тип ais `ai-analytics-plan`, зерно portal-month).
// ---------------------------------------------------------------------------

/** Цели одного менеджера на месяц из UF-полей `UF_USR_A_SALES_PLAN_*`. */
export interface ManagerPlanTarget {
    managerId: string;
    /** Продаж в месяц; null — план не задан. */
    sales: number | null;
    /** Звонков в месяц; null — план не задан. */
    calls: number | null;
    /** Презентаций в месяц; null — план не задан. */
    presentations: number | null;
    /** Весь каталог показателей плана: код → значение (null — не задан). */
    targets: Record<string, number | null>;
}

/**
 * Снимок планов месяца: цели снимаются раз в месяц (1-го числа), чтобы
 * копилась история планов и цель месяца не «переезжала» задним числом.
 * Санити цели (§4.9): если план выполняют меньше трети сотрудников за три
 * месяца — план помечается пожеланием, а не планом.
 */
export interface PlanSnapshot {
    /** Месяц снимка 'YYYY-MM'. */
    monthKey: string;
    /** День снятия 'YYYY-MM-DD' в TZ портала. */
    takenOn: string;
    managers: ManagerPlanTarget[];
    /** Доля выполнявших план за окно фактов; null — фактов не хватило. */
    achieversShare: number | null;
    /** Месяцы фактов, по которым считалась доля (не больше трёх). */
    factMonths: string[];
    /** Менеджеров с планом и фактом в окне (знаменатель доли). */
    factManagers: number;
    /** План — пожелание: выполняют меньше трети сотрудников. */
    planIsWish: boolean;
    /** Почему доля не посчитана ('no-facts', 'no-targets'); иначе null. */
    reason: string | null;
}
