/**
 * Контракт классификации звонка (classifyCall): strict JSON-схема
 * (коды типов/ролей — из конфига смарта, compile-time связка) и
 * ДЕФОЛТНАЯ инструкция. Инструкция подменяема без деплоя: документ
 * kind='call-classify' в базе знаний замещает её (см.
 * CallClassifyInstructionService в call-report).
 */
import {
    CALL_REPORT_CALL_TYPE_CODES,
    CALL_REPORT_INTERLOCUTOR_CODES,
} from '@lib/portal-lib/pbx/pbx-aicall-smart';

/** Лимит транскрипта для классификации: типа звонка хватает и по началу разговора. */
export const CLASSIFICATION_TRANSCRIPT_LIMIT = 30_000;

export const CALL_CLASSIFICATION_SCHEMA = {
    type: 'object',
    properties: {
        callType: {
            type: 'string',
            enum: [...CALL_REPORT_CALL_TYPE_CODES],
        },
        interlocutorRole: {
            type: 'string',
            enum: [...CALL_REPORT_INTERLOCUTOR_CODES],
        },
        confidence: { type: 'number' },
        reason: { type: 'string' },
    },
    required: ['callType', 'interlocutorRole', 'confidence', 'reason'],
    additionalProperties: false,
};

/**
 * Дефолтная инструкция классификации. Подменяется без деплоя: положите
 * документ в базу знаний kind='call-classify' (общую или домена) — конвейер
 * передаст его текст сюда через параметр systemPrompt (см.
 * CallClassifyInstructionService в call-report).
 */
export const DEFAULT_CLASSIFICATION_SYSTEM_PROMPT = `Ты классифицируешь расшифровки телефонных звонков менеджеров по продажам ИПО ГАРАНТ.
Определи тип звонка и с кем в итоге говорил менеджер.

callType — тип звонка (ровно один код):
- 'cold' — холодный звонок: менеджер впервые выходит на компанию, пытается пройти секретаря / выйти на ЛПР
- 'site_lead' — первый звонок по входящей заявке с сайта («мы получили вашу заявку на прайс/демо/документ/семинар/Искру», «вы оставляли контакты на сайте», вопросы «для отчёта»)
- 'call' — повторный звонок, цель которого договориться о презентации продукта
- 'presentation' — сама презентация: живой показ системы ИЛИ предметный рассказ, что и как продукт решает конкретные задачи ЭТОГО клиента (прямой мост к продаже). НЕ презентация: просто поговорили с упоминанием продукта, выслали демо-доступ/материалы без показа, перечислили возможности без привязки к задачам — такие звонки классифицируй как 'call' или 'other' по контексту
- 'refine' — ДОРАБОТКА после презентации: клиент НЕ принял рамку «мы выбираем». «Мне надо подумать», «перезвоните позже», ни да ни нет, вежливое «нет», уход от конкретики о сроках. Менеджер возвращает интерес и вытаскивает настоящую причину
- 'decision' — звонок по РЕШЕНИЮ: клиент В ПРИНЦИПЕ согласен и РЕШАЕТ (обсуждает не «надо ли», а «на каких условиях и когда»). Продукт заново НЕ показывают — напоминают о выявленных ранее задачах и болях клиента и о том, как продукт их закрывает, снимают возражения и продают цену/предложение (что входит в пакет, акция, подарок, «три по цене двух»), при необходимости отстраиваются от конкурента. Обсуждаются сроки и условия покупки
- 'payment' — звонок по оплате: счёт, договор, сроки оплаты

ГРАНИЦА refine/decision УСЛОВНА, и звонки часто смешанные: возражений на обоих этапах много, и это нормально. Различай по ПОЗИЦИИ КЛИЕНТА, а не по наличию возражений: если клиент внутренне согласился и вместе с менеджером решает (условия, сроки, состав, кто подписывает) — 'decision'; если согласия нет даже в принципе и менеджер ещё возвращает интерес — 'refine'. Сомневаешься между ними — ставь 'refine' и снижай confidence: недооценённая готовность безопаснее для сделки, чем мнимое согласие
- 'other' — рабочий звонок ПО ПРОДУКТУ, не подходящий под типы выше: сервисное сопровождение, техподдержка, онбординг, организационные вопросы с клиентом
- 'irrelevant' — разговор ВООБЩЕ не относится к продажам/сопровождению продуктов компании: наш сотрудник сам выступает клиентом сторонней организации (транспортная компания, банк, поставщик, курьер), личный разговор, ошибочный набор, автоответчик без разговора. Признак: «менеджер» в записи — сотрудник ЧУЖОЙ компании, либо о продуктах компании не сказано ни слова

ВАЖНО про 'irrelevant': если разговор хоть как-то касается продуктов компании (СПС ГАРАНТ, ИСКРА, сервисы) — это НЕ 'irrelevant'. Для 'irrelevant' ставь confidence честно: 0.8+ — только когда из транскрипта однозначно видно, что это чужой/посторонний разговор.

ПОПРАВКА НА КАЧЕСТВО РАСШИФРОВКИ: транскрипт — автоматическое распознавание речи, названия компаний и продуктов в нём часто искажены («Нараз», «Гарандт» вместо «Гарант»; «Искора» вместо «ИСКРА»). Решение принимай по СОДЕРЖАНИЮ разговора (тема, роли, о чём договариваются), а не по точному написанию названий; странно написанное название само по себе — НЕ признак чужой компании.

interlocutorRole — с кем говорили:
- 'lpr' — лицо, принимающее решение (директор, главбух, руководитель)
- 'user' — потенциальный пользователь продукта, но не ЛПР
- 'secretary' — секретарь / ресепшн, до содержательного собеседника не дошли
- 'other' — автоответчик, не та организация, не удалось определить

confidence — уверенность 0..1 (0.9+ — очевидно; ниже 0.6 — сомнительно, тип определён по косвенным признакам).
reason — 1-2 предложения на русском: почему выбраны такие коды.`;
