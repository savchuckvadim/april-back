/**
 * Ручной прогон аудита сделок по кнопке админки: админка ставит джоб в
 * `QueueNames.EVENT_SALES_DEAL_AUDIT_RUN`, воркер event-sales запускает
 * прогон «как у крона». Тип и параметры общие для обеих сторон очереди.
 */
export interface DealAuditRunNowJobData {
    /** Домен портала: пороги и получатели — из его настроек. */
    readonly domain: string;
}

/**
 * Один джоб на портал: пока он ждёт или идёт, второе нажатие ничего не
 * ставит (иначе сотрудники получили бы сводку дважды).
 */
export const dealAuditRunNowJobId = (domain: string): string =>
    `${domain}:run-now`;

/**
 * Сколько ждать, если идёт другой прогон (лок общий с кроном): попытка
 * раз в минуту в течение 15 минут, потом джоб сдаётся с записью в Telegram.
 * Таймаута у джоба нет: прогон по большой воронке идёт минуты, а повтор по
 * таймауту разослал бы сводки второй раз.
 */
export const DEAL_AUDIT_RUN_NOW_RETRY = {
    attempts: 15,
    backoffMs: 60_000,
} as const;
