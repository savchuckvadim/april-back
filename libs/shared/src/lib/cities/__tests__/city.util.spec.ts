import {
    canonicalCity,
    getCities,
    normalizeCityText,
    sameCity,
} from '../city.util';

describe('города и их написания', () => {
    it.each([
        ['Питер', 'Санкт-Петербург'],
        ['спб', 'Санкт-Петербург'],
        ['ОП САНКТ-ПЕТЕРБУРГ (ОП)', 'Санкт-Петербург'],
        ['Ленинградская область', 'Санкт-Петербург'],
        ['Ростов', 'Ростов-на-Дону'],
        ['Отдел продаж Ростов (ОП)', 'Ростов-на-Дону'],
        ['ОП Воронеж (ОП)', 'Воронеж'],
        ['воронежская область', 'Воронеж'],
    ])('«%s» → %s', (raw, expected) => {
        expect(canonicalCity(raw)).toBe(expected);
    });

    it('незнакомое название — null, а не догадка', () => {
        expect(canonicalCity('Группа Звездочки')).toBeNull();
        expect(canonicalCity('')).toBeNull();
        expect(canonicalCity(null)).toBeNull();
    });

    /*
     * Ночная заявка 18.09.2026: в лиде «Питер», отдел «ОП САНКТ-ПЕТЕРБУРГ
     * (ОП)». Пара должна узнаваться без настроек.
     */
    it('«Питер» и «ОП САНКТ-ПЕТЕРБУРГ (ОП)» — один город', () => {
        expect(sameCity('Питер', 'ОП САНКТ-ПЕТЕРБУРГ (ОП)')).toBe(true);
        expect(sameCity('Питер', 'ОП Воронеж (ОП)')).toBe(false);
        expect(sameCity('Ростов', 'Отдел продаж Ростов (ОП)')).toBe(true);
    });

    /*
     * Сравниваем словами, а не подстрокой: «нн» внутри «Инновации» и «мск»
     * внутри «Томск» городами не являются.
     */
    it('название ищется словом, а не куском слова', () => {
        expect(canonicalCity('Центр Инновации')).toBeNull();
        expect(canonicalCity('Томск')).toBeNull();
        expect(canonicalCity('НН')).toBe('Нижний Новгород');
    });

    it('регистр, ё и дефисы не мешают', () => {
        expect(normalizeCityText('Ростов-на-Дону')).toBe('ростов на дону');
        expect(sameCity('РОСТОВ-НА-ДОНУ', 'ростов')).toBe(true);
    });

    it('список городов отдаётся для подсказок', () => {
        expect(getCities()).toContain('Санкт-Петербург');
    });
});
