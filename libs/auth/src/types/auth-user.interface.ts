import { Role } from './role.enum';

/**
 * Аутентифицированный субъект, который гард кладёт в `request.user` и который
 * потребители получают через декоратор `@CurrentUser()`.
 *
 * Поля `clientId`/`portalId` опциональны и заполняются только для будущей
 * клиентской авторизации (привязка пользователя к client + portal Bitrix).
 * Для SuperUser они отсутствуют.
 */
export interface AuthUser {
    /** Идентификатор субъекта (для SuperUser — его login). */
    sub: string;
    /** Логин субъекта. */
    login: string;
    /** Роль субъекта. */
    role: Role;
    /** Идентификатор клиента (будущая клиентская авторизация). */
    clientId?: number;
    /** Идентификатор портала Bitrix (будущая клиентская авторизация). */
    portalId?: number;
    /**
     * Пользователь — администратор портала Bitrix (portal-context сессия
     * маркетплейса). Проверяется REST-вызовом при обмене сессии, поэтому
     * подделать нельзя. Нужен действиям, которые вправе делать только
     * владелец портала — например смена адреса доставки кода подключения.
     */
    isAdmin?: boolean;
    /**
     * ID пользователя на портале Bitrix (portal-context сессия). Якорь
     * идентичности: связывает корневого пользователя клиента с конкретным
     * человеком на портале (`users.bitrix_id`) и пишется в журнал действий.
     */
    bitrixUserId?: string;
    /**
     * Домен портала Bitrix (portal-context сессия фрейма, выпуск —
     * PortalSessionService). Guard мутирующих ручек сверяет с ним
     * `domain` тела запроса.
     */
    domain?: string;
    /**
     * member_id портала Bitrix24 — постоянный идентификатор портала
     * (сессия маркетплейс/локального приложения, `sub` там тоже member_id).
     * Кабинет находит по нему портал, когда `portalId` в токене нет.
     */
    memberId?: string;
    /**
     * ID учётной записи кабинета клиента (`users.id`): токен входа с сайта
     * или сессия фрейма сотрудника, у которого есть учётка. Роль в портале
     * кабинет берёт из БД (portal_users) — отзыв действует сразу.
     */
    userId?: number;
}

/** Полезная нагрузка JWT — совпадает с {@link AuthUser} плюс стандартные claim-ы. */
export interface AuthJwtPayload extends AuthUser {
    /** Время выпуска (issued at), сек. — проставляется библиотекой jsonwebtoken. */
    iat?: number;
    /** Время истечения (expiration), сек. — проставляется библиотекой jsonwebtoken. */
    exp?: number;
}
